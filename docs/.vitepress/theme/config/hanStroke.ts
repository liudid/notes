export function strokeOf(ch: string): number | null {
  if (!ch) return null;
  if (STROKE_MAP[ch] != null) return STROKE_MAP[ch];
  return null;
}

export function sumStrokes(
  text: string,
  overrides: Record<string, number> = {},
): { total: number; missing: string[]; detail: { ch: string; n: number }[] } {
  const detail: { ch: string; n: number }[] = [];
  const missing: string[] = [];
  let total = 0;
  for (const ch of text.replace(/\s/g, "")) {
    const n = overrides[ch] ?? strokeOf(ch);
    if (n == null || n <= 0) {
      missing.push(ch);
      detail.push({ ch, n: 0 });
    } else {
      total += n;
      detail.push({ ch, n });
    }
  }
  return { total, missing, detail };
}
